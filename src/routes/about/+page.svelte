<h1>About FileVault</h1>
<p class="muted">
	FileVault is a project by Zebraps. It lets analysts download single files (DLLs, executables,
	assets) from games and software, organised per company and product, with SHA-256 hashes so you
	can verify what you fetch.
</p>
<p class="muted">
	Files are provided for research and interoperability purposes. If you are a rights holder and
	want something removed, contact Zebraps.
</p>
